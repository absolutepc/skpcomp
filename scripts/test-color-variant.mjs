import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
const exports={};
runInNewContext(ts.transpileModule(readFileSync('lib/product-color-variant.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,structuredClone});
const {createColorVariant,saveColorVariant}=exports;
const source={id:'original',name:'Test GPU',category:'gpu',price:70000,art:'gpu',description:'Description',image:'/products/photos/original.webp',gallery:['https://example.com/photo.png'],stock:false,brand:'PALIT',socket:'',memory:'',watts:250,colorHex:'#FFFFFF',specs:{color:'Белый',gpuChipBrand:'NVIDIA',cudaCores:'6144',brandSeries:'GamingPro'},buildComponents:{gpu:'RTX 5070'},buildExtras:[{name:'Extra',value:'Part'}]};
const snapshot=JSON.stringify(source);
const draft=createColorVariant(source,'product-new');
assert.equal(draft.id,'product-new');
for(const field of ['name','category','price','art','description','stock','brand','socket','memory','watts'])assert.equal(draft[field],source[field]);
assert.equal(draft.image,'');assert.equal(draft.gallery.length,0);assert.equal(draft.colorHex,'');assert.equal(draft.specs.color,'');
assert.equal(draft.specs.cudaCores,'6144');assert.equal(draft.specs.brandSeries,'GamingPro');
assert.throws(()=>saveColorVariant([source],draft,source.id),/название/);
draft.specs.color='Чёрный';
assert.throws(()=>saveColorVariant([source],draft,source.id),/HEX/);
draft.colorHex='#171717';draft.image='https://example.com/new.png';
draft.specs.cudaCores='6000';draft.buildComponents.gpu='Other GPU';draft.buildExtras[0].value='Other';
assert.equal(JSON.stringify(source),snapshot,'Draft changes and cancelling do not mutate original');
const saved=saveColorVariant([source],draft,source.id);
assert.equal(saved.length,2);assert.equal(saved[0].variantGroup,saved[1].variantGroup);
assert.equal(saved[0].image,source.image);assert.equal(saved[0].specs.cudaCores,'6144');
assert.equal(saved[1].image,'https://example.com/new.png');assert.equal(saved[1].specs.cudaCores,'6000');
assert.equal(JSON.stringify(source),snapshot,'Saving builds a new array without mutating current data');
const grouped={...source,variantGroup:'existing-colors'};
const third=createColorVariant(grouped,'product-third');
assert.equal(third.variantGroup,'existing-colors');
const linked=saveColorVariant([grouped],{...third,colorHex:'#FF0000',specs:{color:'Красный'}},source.id);
assert.equal(linked[1].variantGroup,'existing-colors');
assert.throws(()=>saveColorVariant([],draft,source.id),/не найден/);
assert.throws(()=>saveColorVariant(saved,draft,source.id),/уже существует/);
assert.throws(()=>saveColorVariant([source],{...draft,category:'cpu'},source.id),/категории/);
console.log('Color variant tests passed: parameter copying, independent media, grouping, cancellation and validation.');
