import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const mobile=read('app/admin/qr/approve/page.tsx');
const approvalLayout=read('app/admin/qr/approve/layout.tsx');
assert.match(approvalLayout,/index:false/);
assert.match(approvalLayout,/follow:false/);
assert.match(approvalLayout,/referrer:'no-referrer'/);
const desktop=read('app/admin-qr-login.tsx');
const verifier=read('lib/admin-passkey-verify.ts');
const decision=read('app/api/admin/qr/decision/route.ts');
assert.match(mobile,/navigator\.credentials\.get/);
assert.match(mobile,/userVerification:'required'/);
assert.match(mobile,/approved:true/);
assert.match(mobile,/options\.rpID!==window\.location\.hostname/);
assert.match(mobile,/credential\.type!=='public-key'/);
assert.match(mobile,/decision\.status!=='approved'/);
assert.match(mobile,/if\(submitting\.current\|\|approved\)return/);
assert.match(mobile,/submitting\.current=true/);
assert.match(mobile,/finally\{submitting\.current=false;setBusy\(false\)/);
assert.match(mobile,/setApproved\(true\)/);
assert.match(mobile,/e instanceof DOMException&&e\.name==='NotAllowedError'/);
assert.match(mobile,/e instanceof DOMException&&e\.name==='AbortError'/);
assert.match(mobile,/disabled=\{busy\|\|approved\|\|/);
assert.match(mobile,/\/api\/admin\/qr\/options/);
assert.match(mobile,/\/api\/admin\/qr\/decision/);
assert.match(mobile,/Подтверждайте только тот вход/);
assert.doesNotMatch(mobile,/desktopSecret/);
assert.match(desktop,/\/api\/admin\/qr\/consume/);
assert.match(desktop,/Date\.now\(\)>=expiresAtMs/);
assert.match(desktop,/url\.origin===window\.location\.origin/);
assert.match(desktop,/url\.pathname==='\/admin\/qr\/approve'/);
assert.match(desktop,/url\.searchParams\.get\('request'\)===requestToken/);
assert.match(desktop,/url\.searchParams\.size===1/);
assert.match(desktop,/desktopSecret:request\.desktopSecret/);
// The desktop must reject unknown server states before rendering them.
assert.match(desktop,/if\(!\['pending','approved','denied','expired','consumed'\]\.includes\(result\.status\)\)throw Error/);
assert.match(desktop,/setError\(''\);\s*setStatus\(result\.status\)/);
// A superseded create request must not parse or install stale QR data.
assert.match(desktop,/if\(generation!==requestGeneration\.current\)return;\s*const value=await response\.json\(\)/);
assert.match(verifier,/expectedChallenge:Buffer\.from\(challenge,'hex'\)\.toString\('base64url'\)/);
assert.match(decision,/verifyAdminPasskeyAssertion/);
assert.match(decision,/markQrApprovedAfterVerification/);
console.log('Mobile QR Passkey approval security wiring passed.');
