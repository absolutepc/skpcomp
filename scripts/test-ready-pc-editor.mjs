import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';

const cache=new Map();
function load(name){
 if(cache.has(name))return cache.get(name);
 const exports={};cache.set(name,exports);
 const file='lib/'+name+'.ts';
 const input=readFileSync(new URL('../'+file,import.meta.url),'utf8');
 const compiled=ts.transpileModule(input,{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
 runInNewContext(compiled.outputText,{exports,require:id=>load(id.replace('./','')),Array,Set,Map,Math,Number,JSON});
 return exports;
}
const {seed}=load('seed');
const {readyCandidateErrors,readyBuildErrors,resolveReadyPart,readyBuildSelection}=load('ready-pc-compatibility');
const {getBuildRows}=load('build-components');
const by=id=>seed.products.find(p=>p.id===id);
const cpu=by('ryzen-7500f'),board=by('b650'),ram=by('ddr5-32'),chassis=by('case-white');
const cpu4={...cpu,id:'test-cpu-am4',name:'Test Ryzen AM4',socket:'AM4',memory:'DDR4',specs:{socket:'AM4',memory:'DDR4'}};
const board4={...board,id:'test-board-am4',name:'Test AM4 DDR4 Board',socket:'AM4',memory:'DDR4',specs:{socket:'AM4',memory:'DDR4',form:'mATX'}};
const ram4={...ram,id:'test-ram-ddr4',name:'Test DDR4 Memory',memory:'DDR4',specs:{memory:'DDR4',modules:'2',capacity:'16'}};
const gpu={...by('rtx-5070'),id:'test-large-gpu',name:'Test 330mm Triple Slot GPU',specs:{length:'330',slots:'3'}};
const tight={...chassis,id:'test-tight-case',name:'Test Case 300mm GPU Max',specs:{boardForm:'mATX',gpuLength:'300',gpuThicknessSlots:'2',coolerHeight:'150',psuLength:'140',topRadiator:'240'}};
const psu={...by('psu-750'),id:'test-long-psu',name:'Test PSU 170mm',specs:{watts:'750',length:'170',form:'ATX'}};
const cooler={...by('cooler'),id:'test-360mm-cooler',name:'Test Radiator 360mm',specs:{socket:'AM5',radiator:'360',height:'170'}};
const all=[...seed.products,cpu4,board4,ram4,gpu,tight,psu,cooler];
const codes=(slot,part,selection)=>readyCandidateErrors(slot,part,selection,all).map(issue=>issue.code);
assert.ok(codes('motherboard',board4,{cpu:cpu.name}).includes('cpu-socket'),'CPU first blocks wrong board socket');
assert.ok(codes('cpu',cpu,{motherboard:board4.name}).includes('cpu-socket'),'Board first blocks wrong CPU socket');
assert.ok(codes('ram',ram4,{motherboard:board.name}).some(code=>code.startsWith('ram-')),'DDR5 board blocks DDR4 RAM');
assert.ok(codes('motherboard',board,{ram:ram4.name}).some(code=>code.startsWith('ram-')),'DDR4 RAM blocks DDR5 board');
assert.ok(codes('ram',ram,{motherboard:board4.name}).some(code=>code.startsWith('ram-')),'DDR4 board blocks DDR5 RAM');
assert.ok(codes('motherboard',board4,{ram:ram.name}).some(code=>code.startsWith('ram-')),'DDR5 RAM blocks DDR4 board');
assert.ok(codes('gpu',gpu,{case:tight.name}).includes('case-gpu'),'Case first blocks oversize GPU');
assert.ok(codes('case',tight,{gpu:gpu.name}).includes('case-gpu'),'GPU first blocks undersize case');
assert.ok(codes('gpu',gpu,{case:tight.name}).includes('case-gpu-slots'),'Check GPU slot thickness');
assert.ok(codes('psu',psu,{case:tight.name}).includes('case-psu-length'),'Check PSU length');
assert.ok(codes('cooler',cooler,{case:tight.name}).includes('case-radiator'),'Check radiator mount');
assert.ok(codes('cooler',cooler,{case:tight.name}).includes('case-cooler'),'Check cooler height');
assert.ok(readyBuildErrors({cpu:cpu.name,motherboard:board4.name},all).some(issue=>issue.code==='cpu-socket'),'Cannot save incompatible known pair');
assert.equal(codes('motherboard',board,{cpu:cpu.name,ram:ram.name}).length,0,'Compatible combination allowed');
assert.equal(codes('gpu',by('rtx-5070'),{case:chassis.name}).length,0,'Missing case dimensions are not treated as incompatible');
assert.equal(resolveReadyPart('cpu',cpu.name,all)?.id,cpu.id,'Names resolve to catalog IDs without storing IDs');
assert.equal(readyBuildSelection({cpu:'Legacy unknown model'},all).cpu,undefined,'Unrecognized legacy names remain intact');
const product={buildComponents:{cpu:cpu.name,os:'Windows 11'},buildExtras:[{name:'Вентиляторы',value:'Test Fan'}]};
const rows=getBuildRows(product);
assert.equal(rows.some(row=>row.key==='os'),false,'OS does not appear in public components');
assert.equal(rows.some(row=>row.key==='cpu'),true);
assert.equal(rows.some(row=>row.key.startsWith('extra-')),true);
const shop=readFileSync(new URL('../app/shop.tsx',import.meta.url),'utf8');
assert.match(shop,/Сохранить изменения/);
assert.match(shop,/readyBuildErrors\(editing\.buildComponents,data\.products\)/);
assert.doesNotMatch(shop,/>Не указана<\/button>/);
console.log('Ready PC editor compatibility tests passed: socket, memory, dimensions, selection order, save guard and hidden OS.');
