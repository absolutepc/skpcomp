import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const schema=read('db/admin-employee-invites-schema.sql');
const helper=read('lib/admin-employee-invitations.ts');
const route=read('app/api/admin/staff/route.ts');
assert.match(schema,/token_hash TEXT NOT NULL UNIQUE/);
assert.match(schema,/expires_at TIMESTAMPTZ NOT NULL/);
assert.match(schema,/consumed_at TIMESTAMPTZ/);
assert.match(schema,/revoked_at TIMESTAMPTZ/);
assert.match(helper,/randomBytes\(32\)/);
assert.match(helper,/createHash\('sha256'\)/);
assert.match(helper,/owner.role='owner' AND owner.status='active'/);
assert.match(helper,/target.role='admin' AND target.status='active'/);
assert.match(helper,/i.consumed_at IS NULL AND i.revoked_at IS NULL/);
assert.match(route,/activeSessionOwnerId\(request\)/);
assert.match(route,/issueEmployeeInvitation\(ownerId,userId as string\)/);
assert.doesNotMatch(helper,/INSERT INTO skp_admin_sessions_v2/);
console.log('Employee invitation issuance invariants passed.');
