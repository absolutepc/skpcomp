import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync('lib/product-brands.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {brandsForCategory,canonicalBrand,selectedBrand,popularBrands}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const products=[{category:'cpu',brand:'ASUS'},{category:'gpu',brand:'PALIT'},{category:'mouse',brand:'logitech'},{category:'mouse',brand:'Logitech'},{category:'ram',brand:'Corsair'}];
assert.deepEqual(brandsForCategory('cpu',products),['AMD','Intel']);
assert.deepEqual(brandsForCategory('gpu',products),['NVIDIA','AMD','Intel']);
assert.equal(brandsForCategory('mouse',products).filter(b=>b==='Logitech').length,1);
assert(!brandsForCategory('cpu',products).includes('Logitech'));
assert(brandsForCategory('ram',products).includes('Corsair'));
assert(!brandsForCategory('ssd',products).includes('Corsair'));
assert.equal(canonicalBrand('ASUS ROG'),'ASUS');
assert.equal(canonicalBrand('intel'),'Intel');
assert.equal(selectedBrand({category:'gpu',brand:'GeForce'},products),'NVIDIA');
assert.equal(selectedBrand({category:'cpu',brand:'Logitech'},products),'');
assert.equal(new Set(popularBrands.map(b=>b.toLowerCase())).size,popularBrands.length);
console.log('Brand category restrictions, aliases, duplicates and category switching passed.');
