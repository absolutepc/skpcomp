import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync('lib/product-brands.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {brandsForCategory,canonicalBrand,selectedBrand,popularBrands,seriesForBrand,selectedSeries,gpuChipBrand,gpuChipBrands,gpuBrandsForChip}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const products=[{category:'cpu',brand:'ASUS'},{category:'gpu',brand:'PALIT'},{category:'mouse',brand:'logitech'},{category:'mouse',brand:'Logitech'},{category:'ram',brand:'Corsair'}];
assert.deepEqual(brandsForCategory('cpu',products),['AMD','Intel']);
assert(brandsForCategory('gpu',products).includes('PALIT'),'Palit boards must be selectable');
assert(brandsForCategory('gpu',products).includes('ASUS'));
assert(brandsForCategory('gpu',products).includes('MSI'));
assert(brandsForCategory('gpu',products).includes('GIGABYTE'));
assert(brandsForCategory('gpu',products).includes('ASRock'));
assert.deepEqual([...gpuChipBrands],['NVIDIA','AMD','Intel']);
assert(gpuBrandsForChip('NVIDIA').includes('PALIT'));
assert(!gpuBrandsForChip('AMD').includes('PALIT'),'Do not offer Palit for Radeon');
assert(!gpuBrandsForChip('Intel').includes('PALIT'),'Do not offer Palit for Arc');
assert(gpuBrandsForChip('AMD').includes('Sapphire'));
assert(gpuBrandsForChip('Intel').includes('ASRock'));
assert(!gpuBrandsForChip('NVIDIA').includes('Sapphire'));
assert.equal(gpuChipBrand({name:'Palit GeForce RTX 5070',brand:'PALIT',specs:{}}),'NVIDIA');
assert.equal(gpuChipBrand({name:'ASRock Radeon RX 9070 XT',brand:'ASRock',specs:{}}),'AMD');
assert.equal(gpuChipBrand({name:'ASRock Arc B580',brand:'ASRock',specs:{}}),'Intel');
assert.equal(gpuChipBrand({name:'MSI Gaming GeForce RTX 5080',brand:'MSI',specs:{gpuChipBrand:'AMD'}}),'AMD','Explicit GPU platform wins');
assert.equal(selectedBrand({category:'gpu',name:'Palit RTX 5070',brand:'PALIT',specs:{}},products),'PALIT');
assert.equal(selectedBrand({category:'gpu',name:'Palit Radeon RX 9070',brand:'PALIT',specs:{}},products),'');
assert.equal(selectedBrand({category:'gpu',name:'GeForce RTX 5070',brand:'GeForce',specs:{}},products),'NVIDIA','Legacy reference brand stays valid');
assert.equal(brandsForCategory('mouse',products).filter(b=>b==='Logitech').length,1);
assert(!brandsForCategory('cpu',products).includes('Logitech'));
assert(brandsForCategory('ram',products).includes('Corsair'));
assert(!brandsForCategory('ssd',products).includes('Corsair'));
assert.equal(canonicalBrand('ASUS ROG'),'ASUS');
assert.equal(canonicalBrand('intel'),'Intel');
assert.equal(selectedBrand({category:'gpu',brand:'GeForce'},products),'NVIDIA');
assert.equal(selectedBrand({category:'cpu',brand:'Logitech'},products),'');
assert.equal(new Set(popularBrands.map(b=>b.toLowerCase())).size,popularBrands.length);
console.log('Brand category restrictions, aliases, duplicates and category switching passed.');

assert(seriesForBrand('PALIT','gpu').includes('GameRock'));
assert(seriesForBrand('MSI','gpu').includes('SUPRIM'));
assert(seriesForBrand('GIGABYTE','gpu').includes('AORUS'));
assert(seriesForBrand('ASUS','gpu').includes('ROG Astral'));
assert.equal(selectedSeries({brand:'PALIT',category:'gpu',specs:{brandSeries:'Infinity 3'}}),'Infinity 3');
assert(seriesForBrand('ASUS','motherboard').includes('ROG'));
assert(seriesForBrand('msi','motherboard').includes('MAG'));
assert(seriesForBrand('MSI','motherboard').includes('MEG'));
assert(seriesForBrand('MSI','motherboard').includes('MPG'));
assert(seriesForBrand('GIGABYTE','motherboard').includes('AORUS'));
assert(!seriesForBrand('ASUS','cpu').includes('ROG'));
assert.equal(selectedSeries({brand:'MSI',category:'motherboard',specs:{brandSeries:'ROG'}}),'');
assert.equal(selectedSeries({brand:'ASUS ROG',category:'motherboard'}),'ROG');
assert.equal(selectedSeries({brand:'ASUS',category:'motherboard',specs:{brandSeries:'TUF Gaming'}}),'TUF Gaming');
assert.equal(selectedSeries({brand:'ASUS ROG',category:'motherboard',specs:{brandSeries:''}}),'');
const editor=fs.readFileSync('app/shop.tsx','utf8');
assert(editor.includes('Производитель графического процессора'),'GPU chip selector is visible in editor');
assert(editor.includes('Производитель видеокарты'),'GPU board-maker selector has a distinct label');
assert(editor.includes('gpuBrandsForChip(gpuChipBrand(editing))'),'Available GPU makers depend on chip vendor');
console.log('Brand series dependencies and legacy ASUS ROG compatibility passed.');
